import hashlib

def seed_flagship_schemes():
    db = SessionLocal()
    added = 0
    now_iso = datetime.now(timezone.utc).isoformat()
    now_dt = datetime.now(timezone.utc)

    for item in FLAGSHIP_SCHEMES:
        # Check if already exists by title
        existing = db.scalars(
            select(SchemeCandidate).where(
                (SchemeCandidate.title == item["title"]) | (SchemeCandidate.title_mr == item["title_mr"])
            )
        ).first()

        if existing:
            # Update fields to ensure accurate Marathi and metadata
            existing.title_mr = item["title_mr"]
            existing.category = item["category"]
            existing.department = item["department"]
            existing.target_beneficiaries = item["target_beneficiaries"]
            existing.benefits = item["benefits"]
            existing.eligibility = item["eligibility"]
            existing.documents_required = item["documents_required"]
            existing.application_process = item["application_process"]
            existing.official_apply_url = item["official_apply_url"]
            existing.current_window_status = item["current_window_status"]
            existing.application_start_date = item["application_start_date"]
            existing.application_deadline = item["application_deadline"]
            existing.verification_status = "verified"
            continue

        url_sha = hashlib.sha256(item["source_url"].encode("utf-8")).hexdigest()
        content_sha = hashlib.sha256(item["text"].encode("utf-8")).hexdigest()

        cand = SchemeCandidate(
            title=item["title"],
            title_mr=item["title_mr"],
            department=item["department"],
            category=item["category"],
            target_beneficiaries=item["target_beneficiaries"],
            application_mode=item["application_mode"],
            source_url=item["source_url"],
            source_url_sha256=url_sha,
            content_sha256=content_sha,
            official_apply_url=item["official_apply_url"],
            brief_description=item["brief_description"],
            benefits=item["benefits"],
            eligibility=item["eligibility"],
            documents_required=item["documents_required"],
            application_process=item["application_process"],
            current_window_status=item["current_window_status"],
            application_start_date=item["application_start_date"],
            application_deadline=item["application_deadline"],
            source_type=item["source_type"],
            verification_status=item["verification_status"],
            provider_classification=item["provider_classification"],
            text=item["text"],
            pdf_urls="",
            retrieved_at_utc=now_iso,
            imported_at=now_dt,
            last_checked_at=now_dt,
            last_reviewed_at=now_dt,
            reviewed_by="admin_seed",
            is_recently_announced=True,
            is_recently_updated=False,
        )
        db.add(cand)
        db.flush()

        # Add window
        win = SchemeApplicationWindow(
            scheme_id=cand.id,
            window_name="Annual Application Cycle",
            start_date=item["application_start_date"],
            deadline_date=item["application_deadline"],
            closing_time="23:59:59",
            window_status=item["current_window_status"],
            date_verification_status="verified",
            official_source_url=item["source_url"],
            notes="Authoritative state government scheme window.",
        )
        db.add(win)
        added += 1

    db.commit()
    total = db.scalar(select(SchemeCandidate.id).order_by(SchemeCandidate.id.desc()))
    print(f"Added {added} new flagship schemes. Highest scheme ID: {total}")
    db.close()


if __name__ == "__main__":
    seed_flagship_schemes()
