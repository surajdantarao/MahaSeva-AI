def sync_sources():
    print(f"Total verified Maharashtra sources: {len(SOURCES)}")
    sites_json_path = ROOT / "sites.json"
    data = {"sites": SOURCES}
    sites_json_path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Updated {sites_json_path} successfully.")

    with SessionLocal() as db:
        synced_count = 0
        for s in SOURCES:
            existing = db.query(ConfiguredSource).filter(ConfiguredSource.name == s["name"]).first()
            if not existing:
                src = ConfiguredSource(
                    name=s["name"],
                    department=s["department"],
                    source_category=s["category"],
                    start_urls=";".join(s["start_urls"]),
                    allowed_domains=";".join(s["allowed_domains"]),
                    provider_hint=s.get("provider_hint", "state"),
                    is_active=s.get("enabled_status", True),
                    monitoring_frequency_hours=12 if "12" in s.get("monitoring_schedule", "") else 24,
                    priority="high" if "ladki" in s["name"].lower() or "dbt" in s["name"].lower() else "medium",
                    verification_required=True,
                )
                db.add(src)
                synced_count += 1
            else:
                existing.department = s["department"]
                existing.source_category = s["category"]
                existing.start_urls = ";".join(s["start_urls"])
                existing.allowed_domains = ";".join(s["allowed_domains"])
                existing.is_active = s.get("enabled_status", True)
        db.commit()
        total_in_db = db.query(ConfiguredSource).count()
        print(f"Synced {synced_count} new sources into database. Total in DB: {total_in_db}")


if __name__ == "__main__":
    sync_sources()
